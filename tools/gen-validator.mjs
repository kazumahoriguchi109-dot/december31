// Pre-generates the save validator from data/save.schema.json so the shipped game never compiles a schema at run time
// (no eval / new Function). Run: node tools/gen-validator.mjs   (and --check to fail if the committed file is stale)
import fs from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const schema = JSON.parse(fs.readFileSync(root + 'data/save.schema.json', 'utf8'));
// date-time is checked in the semantic pass; the schema pass checks structure only
const ajv = new Ajv2020({ code: { source: true, esm: true }, allErrors: true, strict: false, validateFormats: false });
const validate = ajv.compile(schema);
// standalone code still pulls one runtime helper through require(); turn it into an ES import so it runs in a browser
let body = standaloneCode(ajv, validate);
const req = 'require("ajv/dist/runtime/ucs2length").default';
if (!body.includes(req)) throw new Error('expected the ucs2length require in the generated validator');
body = body.replace(req, 'ucs2length');
if (/\brequire\(/.test(body)) throw new Error('generated validator still contains require()');
const out = '// GENERATED by tools/gen-validator.mjs from data/save.schema.json. Do not edit.\nimport * as ucs2mod from "ajv/dist/runtime/ucs2length.js";\n// CJS interop differs between Node, Vite dev and the shipped bundle: unwrap .default until a function appears\nconst ucs2length = (() => { let f = ucs2mod; for (let i = 0; i < 4 && typeof f !== "function"; i++) f = f.default; if (typeof f !== "function") throw new Error("ucs2length unavailable"); return f; })();\n' + body;
const target = root + 'src/content/generated/saveValidator.mjs';
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (cur !== out) { console.error('saveValidator.mjs is stale; run node tools/gen-validator.mjs'); process.exit(1); }
  console.log('saveValidator.mjs is current');
} else {
  fs.writeFileSync(target, out);
  console.log('wrote', target, out.length, 'bytes');
}
